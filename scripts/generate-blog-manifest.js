#!/usr/bin/env node

/**
 * Blog manifest generator for Kuroma.dev
 * Scans ./blogs for BLOG_*.js files and writes blogs/manifest.js, so new posts
 * are picked up by dropping a file in the folder + rerunning this; no hand-edited
 * list in blog-loader.js. GitHub Pages serves no directory index, hence the manifest.
 */

const fs = require('fs');
const path = require('path');

const BLOGS_DIR = path.join(__dirname, '../blogs');
const OUTPUT = path.join(BLOGS_DIR, 'manifest.js');

const files = fs
  .readdirSync(BLOGS_DIR)
  .filter((f) => f.startsWith('BLOG_') && f.endsWith('.js'))
  .map((f) => f.replace(/\.js$/, ''))
  .sort();

const js =
  '// AUTO-GENERATED by scripts/generate-blog-manifest.js; do not edit by hand.\n' +
  '// Rerun `node scripts/generate-blog-manifest.js` after adding/removing a blog.\n' +
  `window.BLOG_MANIFEST = ${JSON.stringify(files, null, 2)};\n`;

fs.writeFileSync(OUTPUT, js, 'utf8');
console.log(`Blog manifest generated: ${OUTPUT} (${files.length} posts)`);
